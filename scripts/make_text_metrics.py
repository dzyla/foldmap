"""Write src/foldmap/text_metrics.py: the advance widths and pair kerning of Liberation Sans Bold
(metrically equal to Arial Bold, the figures' first font), so the layout measures its labels the same way on
every machine, whatever fonts are installed.

    python scripts/make_text_metrics.py [/path/to/LiberationSans-Bold.ttf]
"""

from __future__ import annotations

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

FONT = Path("/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf")
OUT = Path(__file__).resolve().parent.parent / "src" / "foldmap" / "text_metrics.py"
HEADER = (
    "# SPDX-License-Identifier: AGPL-3.0-or-later\n"
    "# Copyright (C) 2026 Dawid Zyla. Additional terms (AGPL-3.0 section 7(b)): see NOTICE.\n"
)
CHARS = "".join(chr(c) for c in range(0x20, 0x7F)) + "′″‴·–—αβγδεηθλπστω"  # what names are written with


def _quote(s: str) -> str:
    """A string literal as ruff format writes it: double quotes unless the text holds one and no single quote."""
    if '"' in s and "'" not in s:
        return repr(s)
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(path: Path) -> None:
    font = TTFont(path)
    cmap, hmtx = font.getBestCmap(), font["hmtx"]
    units = font["head"].unitsPerEm
    glyph = {c: cmap[ord(c)] for c in CHARS if ord(c) in cmap}
    rows = {c: hmtx[g][0] for c, g in glyph.items()}
    pairs = {}
    for table in font["kern"].kernTables if "kern" in font else []:
        for (a, b), v in sorted(table.kernTable.items()):
            for ca in (c for c, g in glyph.items() if g == a):
                for cb in (c for c, g in glyph.items() if g == b):
                    if v:
                        pairs[ca + cb] = v
    version = font["name"].getDebugName(5)
    lines = [
        *HEADER.splitlines(),
        '"""Text metrics of Liberation Sans Bold (metrically Arial Bold; SIL Open Font License 1.1), generated by',
        f'scripts/make_text_metrics.py from {path.name} ({version}). Do not edit by hand."""',
        "",
        f"UNITS = {units}  # font units per em",
        "ADVANCE = {  # character: advance width, font units",
        *(f"    {_quote(c)}: {v!r}," for c, v in rows.items()),
        "}",
        "KERN = {  # character pair: kerning added between them, font units",
        *(f"    {_quote(k)}: {v}," for k, v in pairs.items()),
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}: {len(rows)} characters, {len(pairs)} kerning pairs")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else FONT)
